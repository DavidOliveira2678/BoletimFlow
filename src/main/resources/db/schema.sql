CREATE TABLE IF NOT EXISTS aluno (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    matricula  VARCHAR(20)  NOT NULL UNIQUE,
    nome       VARCHAR(120) NOT NULL,
    email      VARCHAR(120)
);

CREATE TABLE IF NOT EXISTS disciplina (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome          VARCHAR(80) NOT NULL UNIQUE,
    carga_horaria INT         NOT NULL
);

CREATE TABLE IF NOT EXISTS nota (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    aluno_id      BIGINT       NOT NULL,
    disciplina_id BIGINT       NOT NULL,
    bimestre      TINYINT      NOT NULL,
    valor         DECIMAL(4,2) NOT NULL,
    CONSTRAINT fk_nota_aluno      FOREIGN KEY (aluno_id)      REFERENCES aluno(id),
    CONSTRAINT fk_nota_disciplina FOREIGN KEY (disciplina_id) REFERENCES disciplina(id),
    CONSTRAINT uk_nota UNIQUE (aluno_id, disciplina_id, bimestre),
    CONSTRAINT ck_nota_valor    CHECK (valor BETWEEN 0 AND 10),
    CONSTRAINT ck_nota_bimestre CHECK (bimestre BETWEEN 1 AND 4)
);
